using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace RecursiveAI.OneDocument.Generators;

/// <summary>
/// Generates, at compile time, the member lookup that lets the template engine read plain classes without reflection (which NativeAOT and trimming
/// cannot keep). It looks for types marked <c>[TemplateModel]</c> and adds, to each, an implementation of <c>ITemplateObject</c> that hands out every
/// public readable property and field by name. Problems are reported as diagnostics OOTPL001 and OOTPL002.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class TemplateModelGenerator : IIncrementalGenerator
{
    private const string Attribute = "RecursiveAI.OneDocument.Templating.TemplateModelAttribute";

    private static readonly DiagnosticDescriptor NotPartial = new(
        "OOTPL001", "Template model must be partial", "'{0}' is marked [TemplateModel] but it, or a type that contains it, is not declared partial",
        "OneDocument.Templating", DiagnosticSeverity.Error, true);

    private static readonly DiagnosticDescriptor GenericType = new(
        "OOTPL002", "Generic template models are not supported", "'{0}' is, or is inside, a generic type; mark a closed type instead",
        "OneDocument.Templating", DiagnosticSeverity.Error, true);

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<Output> models = context.SyntaxProvider.ForAttributeWithMetadataName(
            Attribute,
            static (node, _) => node is TypeDeclarationSyntax,
            static (ctx, ct) => Build(ctx, ct));

        context.RegisterSourceOutput(models, static (spc, o) =>
        {
            if (o.Diagnostic is { } d)
            {
                spc.ReportDiagnostic(Diagnostic.Create(d.Descriptor, d.Location, d.Argument));
            }

            if (o.Source is not null)
            {
                spc.AddSource(o.HintName!, SourceText.From(o.Source, Encoding.UTF8));
            }
        });
    }

    private sealed class Output
    {
        public string? HintName;
        public string? Source;
        public (DiagnosticDescriptor Descriptor, Location Location, string Argument)? Diagnostic;
    }

    private static Output Build(GeneratorAttributeSyntaxContext ctx, CancellationToken ct)
    {
        var output = new Output();
        if (ctx.TargetSymbol is not INamedTypeSymbol type)
        {
            return output;
        }

        string display = type.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat);
        Location location = type.Locations.FirstOrDefault() ?? Location.None;
        var chain = new List<INamedTypeSymbol>();
        for (INamedTypeSymbol? t = type; t is not null; t = t.ContainingType)
        {
            chain.Insert(0, t);
        }

        if (chain.Any(t => t.IsGenericType))
        {
            output.Diagnostic = (GenericType, location, display);
            return output;
        }

        foreach (INamedTypeSymbol t in chain)
        {
            foreach (SyntaxReference reference in t.DeclaringSyntaxReferences)
            {
                if (reference.GetSyntax(ct) is TypeDeclarationSyntax decl && !decl.Modifiers.Any(m => m.Text == "partial"))
                {
                    output.Diagnostic = (NotPartial, location, display);
                    return output;
                }
            }
        }

        var names = new List<string>();
        for (INamedTypeSymbol? t = type; t is not null && t.SpecialType != SpecialType.System_Object; t = t.BaseType)
        {
            foreach (ISymbol member in t.GetMembers())
            {
                if (member.IsStatic || member.DeclaredAccessibility != Accessibility.Public || member.IsImplicitlyDeclared)
                {
                    continue;
                }

                bool readable = member switch
                {
                    IPropertySymbol p => p.GetMethod is { DeclaredAccessibility: Accessibility.Public } && p.Parameters.Length == 0 && !p.Type.IsRefLikeType && p.Type.TypeKind != TypeKind.Pointer,
                    IFieldSymbol f => !f.Type.IsRefLikeType && f.Type.TypeKind != TypeKind.Pointer,
                    _ => false,
                };
                if (readable && !names.Contains(member.Name))
                {
                    names.Add(member.Name);
                }
            }
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable");
        string ns = type.ContainingNamespace.IsGlobalNamespace ? string.Empty : type.ContainingNamespace.ToDisplayString();
        if (ns.Length > 0)
        {
            sb.Append("namespace ").Append(ns).AppendLine(" {");
        }

        foreach (INamedTypeSymbol t in chain)
        {
            sb.Append("partial ").Append(KeywordOf(t)).Append(' ').Append(t.Name);
            if (SymbolEqualityComparer.Default.Equals(t, type))
            {
                sb.Append(" : global::RecursiveAI.OneDocument.Templating.ITemplateObject");
            }

            sb.AppendLine(" {");
        }

        sb.AppendLine("bool global::RecursiveAI.OneDocument.Templating.ITemplateObject.TryGetTemplateMember(string name, out object? value) {");
        sb.AppendLine("    switch (name) {");
        foreach (string n in names)
        {
            sb.Append("        case ").Append(Literal(n)).Append(": value = this.").Append(Identifier(n)).AppendLine("; return true;");
        }

        sb.AppendLine("    }");
        foreach (string n in names)
        {
            sb.Append("    if (string.Equals(name, ").Append(Literal(n)).Append(", global::System.StringComparison.OrdinalIgnoreCase)) { value = this.").Append(Identifier(n)).AppendLine("; return true; }");
        }

        sb.AppendLine("    value = null; return false;");
        sb.AppendLine("}");
        foreach (INamedTypeSymbol unused in chain)
        {
            sb.AppendLine("}");
        }

        if (ns.Length > 0)
        {
            sb.AppendLine("}");
        }

        output.HintName = string.Join(".", chain.Select(c => c.Name)).Insert(0, ns.Length > 0 ? ns + "." : string.Empty) + ".TemplateModel.g.cs";
        output.Source = sb.ToString();
        return output;
    }

    private static string KeywordOf(INamedTypeSymbol t) => t.TypeKind switch
    {
        TypeKind.Struct => t.IsRecord ? "record struct" : "struct",
        _ => t.IsRecord ? "record" : "class",
    };

    private static string Identifier(string name) => Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind(name) != Microsoft.CodeAnalysis.CSharp.SyntaxKind.None ? "@" + name : name;

    private static string Literal(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
