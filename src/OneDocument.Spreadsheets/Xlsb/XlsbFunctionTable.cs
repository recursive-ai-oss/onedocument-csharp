    private static readonly Dictionary<string, int> ByName = BuildIndex();

    /// <summary>Gets the number of function numbers in the table (the highest number plus one).</summary>
    public static int Count => Entries.Length;

    /// <summary>Looks a function up by its number.</summary>
    /// <param name="id">The function number (the <c>iftab</c> of PtgFunc, the <c>tab</c> of PtgFuncVar).</param>
    /// <param name="name">The upper-case function name as written in a formula.</param>
    /// <param name="minArguments">The fewest arguments.</param>
    /// <param name="maxArguments">The most arguments.</param>
    /// <returns>True when the number names a function.</returns>
    public static bool TryGet(int id, out string name, out int minArguments, out int maxArguments)
    {
        if ((uint)id < (uint)Entries.Length && Entries[id].Name is { } n)
        {
            name = n;
            minArguments = Entries[id].Min;
            maxArguments = Entries[id].Max;
            return true;
        }

        name = string.Empty;
        minArguments = maxArguments = 0;
        return false;
    }

    /// <summary>Looks a function number up by name.</summary>
    /// <param name="name">The function name, any case.</param>
    /// <param name="id">The function number.</param>
    /// <returns>True when the name is a built-in function reachable by number (not the user-defined marker).</returns>
    public static bool TryGetId(string name, out int id) => ByName.TryGetValue(name, out id);

    private static Dictionary<string, int> BuildIndex()
    {
        var map = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
        for (int i = 0; i < Entries.Length; i++)
        {
            if (Entries[i].Name is { } n && i != 255)
            {
                map.TryAdd(n, i);
            }
        }

        return map;
    }
