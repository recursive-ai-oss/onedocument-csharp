#!/usr/bin/env python3
"""Generates src/OneDocument.Spreadsheets/Biff/FunctionTable.g.cs from the text of [MS-XLS] 2.5.198.17 (Ftab).

Usage: gen_ftab.py <MS-XLS text file made with `pdftotext -layout`> <output .cs>

The spec lists each function with a parameter grammar (`name-params = val, [val]`). The generator keeps the
function name and the fewest/most arguments the grammar allows, which is what a fixed-count `PtgFunc` needs.
"""
import re
import sys


def count(grammar):
    """Returns (min, max) argument counts of one parameter grammar."""
    s = grammar.strip()
    pos = 0

    def seq(end):
        nonlocal pos
        lo = hi = 0
        while pos < len(s) and s[pos] != end:
            c = s[pos]
            if c in ' ,':
                pos += 1
            elif c == '[':
                pos += 1
                a, b = seq(']')
                pos += 1
                hi += b
            elif c == '(':
                pos += 1
                a, b = seq(')')
                pos += 1
                lo += a
                hi += b
            elif c == '*':
                m = re.match(r'\*(\d+)', s[pos:])
                n = int(m.group(1))
                pos += m.end()
                # the repeated group is zero-or-more up to n
                if s[pos] == '(':
                    pos += 1
                    a, b = seq(')')
                    pos += 1
                else:
                    a, b = 1, 1
                hi += b * n
            elif s.startswith('ref', pos) or s.startswith('val', pos):
                pos += 3
                lo += 1
                hi += 1
                if s.startswith(' / ', pos):
                    pos += 3
                    pos += 3
            else:
                pos += 1
        return lo, hi

    return seq('\0')


def main():
    text = open(sys.argv[1], encoding='utf-8').read().split('\n')
    start = next(i for i, l in enumerate(text) if l.startswith('2.5.198.17') and 'Ftab' in l and i > 50000)
    end = next(i for i, l in enumerate(text) if l.startswith('2.5.198.18') and i > start)
    entries = {}
    i = start
    cur = None
    while i < end:
        line = text[i].strip()
        m = re.match(r'^0x([0-9A-F]{4})\s+(\S+)$', line)
        if m:
            cur = int(m.group(1), 16)
            entries[cur] = [m.group(2), '']
        elif cur is not None and line and not line.startswith(('Value', '[MS-XLS]', 'Excel Binary', 'Copyright', 'Release', 'The elements')) \
                and not re.match(r'^\d+ / \d+$', line):
            entries[cur][1] += ' ' + line
        i += 1
    top = max(entries) + 1
    out = []
    out.append('// <auto-generated>')
    out.append('// Generated by tools/Biff/gen_ftab.py from the Ftab table of the Excel binary format specification (2.5.198.17). Do not edit.')
    out.append('// </auto-generated>')
    out.append('#nullable enable')
    out.append('namespace RecursiveAI.OneDocument.Spreadsheets.Biff;')
    out.append('')
    out.append('internal static partial class FunctionTable')
    out.append('{')
    out.append('    // Index = iftab. Null name: not assigned. Fixed = argument count of a PtgFunc (-1 when the function takes a variable count).')
    out.append('    private static readonly (string? Name, sbyte Fixed)[] Entries =')
    out.append('    [')
    for k in range(top):
        if k in entries:
            name, g = entries[k]
            g = g.split('=', 1)[1] if '=' in g else ''
            if 'no parameters' in entries[k][1]:
                lo = hi = 0
            else:
                lo, hi = count(g)
            fixed = lo if lo == hi else -1
            out.append('        ("%s", %d),' % (name, fixed))
        else:
            out.append('        (null, -1),')
    out.append('    ];')
    out.append('}')
    open(sys.argv[2], 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print(len(entries), 'entries, top', top - 1)


main()
