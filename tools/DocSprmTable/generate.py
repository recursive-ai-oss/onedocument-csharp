#!/usr/bin/env python3
"""Writes src/OneDocument.Documents/Doc/Binary/SprmTable.g.cs from the Word binary format specification.

Usage: generate.py <[MS-DOC] .docx> <[MS-OSHARED] .docx> <output .cs>
The specifications are Microsoft Open Specifications documents; this script reads their text only ([MS-DOC] section 2.6 for
the single property modifier values and the Prm0 table; [MS-OSHARED] MSONFC for the numbering formats). Output is deterministic.
"""
import html, re, sys, zipfile

src, shared, out = sys.argv[1], sys.argv[2], sys.argv[3]
x = zipfile.ZipFile(src).read('word/document.xml').decode('utf8')
x = re.sub(r'</w:tc>', '\t', x)
x = re.sub(r'</w:p>', '\n', x)
x = re.sub(r'<w:tab/>', '\t', x)
x = html.unescape(re.sub(r'<[^>]+>', '', x))
L = x.split('\n')

# Section 2.6: each modifier is a line "sprmName" followed by a line "(0xNNNN)".
start = next(i for i, l in enumerate(L) if l.startswith('Character Properties') and 'XE' in l)
end = next(i for i, l in enumerate(L) if i > start and l.startswith('Document Properties') and 'XE' in l) if any(
    i > start and l.startswith('Document Properties') and 'XE' in l for i, l in enumerate(L)) else len(L)
sprms = {}
for i in range(start, end - 1):
    m = re.match(r'^\s*(sprm[A-Za-z0-9_]+)$', L[i])
    v = re.match(r'^\(0x([0-9A-Fa-f]{4})\)', L[i + 1])
    if m and v:
        sprms.setdefault(m.group(1), int(v.group(1), 16))

# Prm0 table: lines "0xNN" then "sprmName" (possibly followed by prose).
p0 = next(i for i, l in enumerate(L) if l.startswith('Prm0') and 'XE' in l)
prm0 = {}
for i in range(p0, p0 + 400):
    m = re.match(r'^\s*0x([0-9A-Fa-f]{2})$', L[i])
    if m and i + 1 < len(L):
        n = re.match(r'^\s*(sprm[A-Za-z0-9_]+)', L[i + 1])
        if n and n.group(1) in sprms:
            prm0.setdefault(int(m.group(1), 16), sprms[n.group(1)])
    if L[i].startswith('Prm1') and 'XE' in L[i]:
        break

def text_of(path):
    x = zipfile.ZipFile(path).read('word/document.xml').decode('utf8')
    x = re.sub(r'</w:tc>', '\t', x)
    x = re.sub(r'</w:p>', '\n', x)
    return html.unescape(re.sub(r'<[^>]+>', '', x)).split('\n')


# [MS-OSHARED] MSONFC: name, value, meaning (the ST_NumberFormat name) rows.
S = text_of(shared)
m0 = next(i for i, l in enumerate(S) if l.strip().startswith('MSONFC') and 'XE' in l)
m1 = next(i for i, l in enumerate(S) if i > m0 and l.strip().startswith('WebScreenSizeEnum') and 'XE' in l)
nfc = {}
for i in range(m0, m1 - 2):
    v = re.match(r'^\s*0x([0-9A-Fa-f]{2})\s*$', S[i + 1]) if i + 2 < m1 else None
    if v and re.match(r'^\s*msonfc', S[i]):
        meaning = S[i + 2].strip()
        if meaning.startswith('Specifies that the sequence will not display'):
            meaning = 'none'
        nfc[int(v.group(1), 16)] = meaning[:1].lower() + meaning[1:]

with open(out, 'w', newline='\n') as f:
    f.write('// <auto-generated>\n// Generated by tools/DocSprmTable/generate.py from [MS-DOC] section 2.6 and the Prm0 table. Do not edit.\n// </auto-generated>\n')
    f.write('namespace RecursiveAI.OneDocument.Doc.Binary;\n\n')
    f.write('internal static partial class SprmTable\n{\n')
    f.write('    // Every single property modifier [MS-DOC] section 2.6 lists, sorted by opcode.\n')
    f.write('    internal static readonly (ushort Opcode, string Name)[] Names =\n    [\n')
    for name, op in sorted(sprms.items(), key=lambda kv: (kv[1], kv[0])):
        f.write('        (0x%04X, "%s"),\n' % (op, name))
    f.write('    ];\n\n')
    f.write('    // [MS-DOC] Prm0 structure: isprm (7 bits) to the single property modifier it stands for.\n')
    f.write('    internal static readonly (byte Isprm, ushort Opcode)[] Prm0 =\n    [\n')
    for k in sorted(prm0):
        f.write('        (0x%02X, 0x%04X),\n' % (k, prm0[k]))
    f.write('    ];\n\n')
    f.write('    // [MS-OSHARED] MSONFC: the numbering format codes and the ST_NumberFormat value each maps to.\n')
    f.write('    internal static readonly (byte Code, string Format)[] NumberFormats =\n    [\n')
    for k in sorted(nfc):
        f.write('        (0x%02X, "%s"),\n' % (k, nfc[k]))
    f.write('    ];\n}\n')
print(len(nfc), 'number formats', len(sprms), 'sprms', len(prm0), 'prm0 entries')
