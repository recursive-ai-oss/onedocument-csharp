using System;
using System.IO;
using System.Linq;
using System.Text.Json;
using RecursiveAI.OneDocument;
using RecursiveAI.OneDocument.Spreadsheets;
using RecursiveAI.OneDocument.Spreadsheets.Templating;

namespace RecursiveAI.OneDocument.Tools.OracleCases;

/// <summary>
/// Workbooks produced by rendering the committed workbook templates (<c>testdata/templates/xlsx</c>), for a desktop application and a
/// validator to open and judge. <c>OracleCases --xlsx-templates TEMPLATES OUT</c> renders every <c>NAME.template.xlsx</c> with its
/// <c>NAME.data.json</c> and writes <c>xl-tpl-NAME.xlsx</c>. Both inputs were generated by the test suite; no downloaded file is read.
/// </summary>
internal static class XlsxTemplateCases
{
    public static int Write(string templates, string output)
    {
        Directory.CreateDirectory(output);
        int count = 0;
        foreach (string file in Directory.EnumerateFiles(templates, "*.template.xlsx").Order(StringComparer.Ordinal))
        {
            string name = Path.GetFileName(file)[..^".template.xlsx".Length];
            using Workbook wb = Workbook.Open(file);
            using JsonDocument json = JsonDocument.Parse(File.ReadAllText(Path.Combine(templates, name + ".data.json")));
            XlsxTemplateBinder.Render(wb, json);
            wb.SaveAs(Path.Combine(output, "xl-tpl-" + name + ".xlsx"));
            count++;
        }

        Console.WriteLine("wrote " + count + " workbooks");
        return 0;
    }
}
