def write(out: Path, name: str, lines: list):
    out.mkdir(parents=True, exist_ok=True)
    (out / name).write_text("\n".join(lines) + "\n", encoding="utf-8")


def tail_after_first_argument(args: str) -> str:
    """The argument text after the first top-level comma (commas inside braces or quotes do not count), with that comma."""
    depth, quoted = 0, False
    for i, ch in enumerate(args):
        if ch == '"':
            quoted = not quoted
        elif not quoted:
            if ch in "{(":
                depth += 1
            elif ch in "})":
                depth -= 1
            elif ch == "," and depth == 0:
                return args[i:]
    return ""


def grid(prefix: str, table: dict) -> list:
    lines = []
    for fn, cases in table.items():
        for i, args in enumerate(cases):
            lines.append(f"{prefix}.{fn}.{i}\ta1\t={fn}({args})")
        for j, extra in enumerate(EXTRA):
            rest = tail_after_first_argument(cases[0])
            lines.append(f"{prefix}.{fn}.x{j}\ta1\t={fn}({extra}{rest})")
    return lines


