#!/usr/bin/env python3
"""Writes src/OneDocument.Presentations/Odf/PresetAdjustNames.g.cs: for every preset geometry, the names of its adjust values in
order, read from the generated preset data (src/OneDocument.Rendering/Drawing/Generated/PresetShapeData.g.cs). ODF stores the
adjust values of an ooxml-* shape as a bare list; PowerPoint accepts only the guide names the preset declares (adj, adj1, hf, ...).
"""
import re, sys
root = sys.argv[1] if len(sys.argv) > 1 else "."
src = open(root + "/src/OneDocument.Rendering/Drawing/Generated/PresetShapeData.g.cs").read()
rows = []
for m in re.finditer(r'^\s+"(\w+)" => "((?:[^"\\]|\\.)*)",?$', src, re.M):
    names = []
    for l in m.group(2).split("\\n"):
        if not l.startswith("A "):
            break  # adjust values come first; later "A" lines are arcTo path commands
        names.append(l.split()[1])
    if names:
        rows.append((m.group(1), names))
out = ["// <auto-generated>", "// Generated by tools/DrawingPresets/adjust-names.py from the ECMA-376 preset shape definitions (see PresetShapeData.g.cs). Do not edit.",
       "// The preset shape definitions are part of ECMA-376; Ecma International's copyright notice applies (see THIRD-PARTY-NOTICES.md).",
       "// </auto-generated>", "#nullable enable", "namespace RecursiveAI.OneDocument.Presentations.Odf;", "",
       "internal static class PresetAdjustNames", "{", "    /// <summary>The adjust value names of a preset geometry in declaration order, or null when it has none.</summary>",
       "    internal static string[]? Of(string preset) => preset switch", "    {"]
for n, names in rows:
    out.append('        "%s" => [%s],' % (n, ", ".join('"%s"' % x for x in names)))
out += ["        _ => null,", "    };", "}", ""]
open(root + "/src/OneDocument.Presentations/Odf/PresetAdjustNames.g.cs", "w").write("\n".join(out))
print(len(rows), "presets with adjust values")
