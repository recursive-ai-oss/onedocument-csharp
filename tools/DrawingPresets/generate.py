#!/usr/bin/env python3
"""Generates src/OneDocument.Rendering/Drawing/Generated/PresetShapeData.g.cs from the preset shape definitions that are part of
ECMA-376 Part 1 (OfficeOpenXML-DrawingMLGeometries.zip, inside ECMA-376-1_5th_edition_december_2016.zip).

    generate.py <ECMA-376-1_5th_edition_december_2016.zip> <output .cs>

The output is deterministic: shapes sorted by name, no timestamps. The input zip must hash to the pinned value.

Each shape becomes one text block, read at run time by PresetShapes:

    A name value            adjust value default (avLst)
    G name op a b c         guide (gdLst), in document order
    R l t r b               text rectangle
    P w h fill stroke       a path: size (0 = shape size), fill mode (n none, x norm, l lighten, L lightenLess, d darken, D darkenLess), stroke 1/0
    M x y | L x y | A wR hR stAng swAng | Q x1 y1 x2 y2 | C x1 y1 x2 y2 x3 y3 | Z      path commands
"""
import hashlib
import io
import sys
import zipfile
import xml.etree.ElementTree as ET

PINNED = "9d0bcad9cf06054785b03762fcfadbf6bab7e54a5f9d69434e34b7fd464d4129"
A = "{http://schemas.openxmlformats.org/drawingml/2006/main}"
FILL = {"norm": "x", "none": "n", "lighten": "l", "lightenLess": "L", "darken": "d", "darkenLess": "D"}


def main() -> None:
    zip_path, out_path = sys.argv[1], sys.argv[2]
    data = open(zip_path, "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != PINNED:
        sys.exit(f"unexpected input {digest}")
    inner = zipfile.ZipFile(io.BytesIO(data)).read("OfficeOpenXML-DrawingMLGeometries.zip")
    xml = zipfile.ZipFile(io.BytesIO(inner)).read("presetShapeDefinitions.xml")
    root = ET.fromstring(xml.lstrip(b"\xef\xbb\xbf"))
    shapes = {}
    for shape in root:
        lines = []
        for gd in shape.findall(f"{A}avLst/{A}gd"):
            lines.append(f"A {gd.get('name')} {gd.get('fmla').split()[1]}")
        for gd in shape.findall(f"{A}gdLst/{A}gd"):
            lines.append(f"G {gd.get('name')} {' '.join(gd.get('fmla').split())}")
        rect = shape.find(f"{A}rect")
        if rect is not None:
            lines.append(f"R {rect.get('l')} {rect.get('t')} {rect.get('r')} {rect.get('b')}")
        for path in shape.findall(f"{A}pathLst/{A}path"):
            fill = FILL[path.get("fill", "norm")]
            stroke = "0" if path.get("stroke") in ("0", "false") else "1"
            lines.append(f"P {path.get('w', '0')} {path.get('h', '0')} {fill} {stroke}")
            for cmd in path:
                tag = cmd.tag[len(A):]
                pts = [(p.get("x"), p.get("y")) for p in cmd.findall(f"{A}pt")]
                flat = " ".join(f"{x} {y}" for x, y in pts)
                if tag == "moveTo":
                    lines.append(f"M {flat}")
                elif tag == "lnTo":
                    lines.append(f"L {flat}")
                elif tag == "arcTo":
                    lines.append(f"A {cmd.get('wR')} {cmd.get('hR')} {cmd.get('stAng')} {cmd.get('swAng')}")
                elif tag == "quadBezTo":
                    lines.append(f"Q {flat}")
                elif tag == "cubicBezTo":
                    lines.append(f"C {flat}")
                elif tag == "close":
                    lines.append("Z")
                else:
                    sys.exit("unknown path command " + tag)
        shapes[shape.tag] = lines
    out = io.StringIO()
    out.write("// <auto-generated>\n")
    out.write("// Generated by tools/DrawingPresets/generate.py from presetShapeDefinitions.xml in ECMA-376 5th edition Part 1\n")
    out.write(f"// (OfficeOpenXML-DrawingMLGeometries.zip, archive sha256 {PINNED}). Do not edit.\n")
    out.write("// The preset shape definitions are part of ECMA-376; Ecma International's copyright notice applies (see THIRD-PARTY-NOTICES.md).\n")
    out.write("// </auto-generated>\n")
    out.write("#nullable enable\n")
    out.write("namespace RecursiveAI.OneDocument.Rendering.Drawing;\n\n")
    out.write("internal static class PresetShapeData\n{\n")
    out.write("    internal static readonly string[] Names =\n    [\n")
    for name in sorted(shapes):
        out.write(f'        "{name}",\n')
    out.write("    ];\n\n")
    out.write("    internal static string? Get(string name) => name switch\n    {\n")
    for name in sorted(shapes):
        body = "\\n".join(shapes[name])
        out.write(f'        "{name}" => "{body}",\n')
    out.write("        _ => null,\n    };\n}\n")
    with open(out_path, "w", newline="\n") as f:
        f.write(out.getvalue())
    print(len(shapes), "shapes")


main()
